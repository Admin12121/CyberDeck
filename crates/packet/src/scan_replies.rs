//! Read-only raw packet response correlation for future authorized active scans.
//! Caller supplies a backend-owned outstanding probe identity and scoped frame
//! bytes. No sending, raw socket acquisition, case selection or target expansion.
//! This intentionally refuses truncated, fragmented and ambiguous responses.
use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProbeTransport {
    TcpSyn,
    Udp,
    IcmpEcho,
    Arp,
    NeighborDiscovery,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ProbeIdentity {
    pub local: IpAddr,
    pub target: IpAddr,
    pub transport: ProbeTransport,
    pub local_port: u16,
    pub target_port: u16,
    /// TCP SYN's initial sequence number, generated by the sending backend.
    pub syn_sequence: Option<u32>,
    /// ICMP echo's identifier and sequence (backend-owned, not user input).
    pub echo_key: Option<(u16, u16)>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReplyEvidence {
    TcpSynAck,
    TcpReset,
    UdpResponse,
    IcmpV4Error { kind: u8, code: u8 },
    IcmpV6Error { kind: u8, code: u8 },
    IcmpEcho,
    ArpReply { hardware_address: [u8; 6] },
    NeighborAdvertisement { hardware_address: [u8; 6] },
}

struct IpPacket<'a> {
    source: IpAddr,
    target: IpAddr,
    protocol: u8,
    hop_limit: u8,
    body: &'a [u8],
}

fn be16(data: &[u8]) -> Option<u16> {
    Some(u16::from_be_bytes(data.get(..2)?.try_into().ok()?))
}

fn raw_ip_packet(packet: &[u8], quoted: bool) -> Option<IpPacket<'_>> {
    match packet.first().copied()? >> 4 {
        4 => {
            if packet.len() < 20 {
                return None;
            }
            let ihl = usize::from(packet[0] & 15) * 4;
            let size = usize::from(be16(&packet[2..4])?);
            if ihl < 20 || ihl > packet.len() || size < ihl || (!quoted && size > packet.len()) {
                return None;
            }
            // Never infer TCP/UDP replies from IPv4 fragments.
            if be16(&packet[6..8])? & 0x3fff != 0 {
                return None;
            }
            let src = IpAddr::V4(Ipv4Addr::new(
                packet[12], packet[13], packet[14], packet[15],
            ));
            let dst = IpAddr::V4(Ipv4Addr::new(
                packet[16], packet[17], packet[18], packet[19],
            ));
            Some(IpPacket {
                source: src,
                target: dst,
                protocol: packet[9],
                hop_limit: packet[8],
                body: &packet[ihl..size.min(packet.len())],
            })
        }
        6 => {
            if packet.len() < 40 {
                return None;
            }
            let payload_len = usize::from(be16(&packet[4..6])?);
            // Refuse jumbograms, including their ambiguous zero length.
            if payload_len == 0 || (!quoted && payload_len > packet.len() - 40) {
                return None;
            }
            let src = IpAddr::V6(Ipv6Addr::from(<[u8; 16]>::try_from(&packet[8..24]).ok()?));
            let dst = IpAddr::V6(Ipv6Addr::from(<[u8; 16]>::try_from(&packet[24..40]).ok()?));
            let end = (40 + payload_len).min(packet.len());
            let mut next = packet[6];
            let mut cursor = 40usize;
            for _ in 0..8 {
                if !matches!(next, 0 | 43 | 44 | 60) {
                    break;
                }
                if cursor + 2 > end {
                    return None;
                }
                let after = packet[cursor];
                let len = if next == 44 {
                    if cursor + 8 > end || be16(&packet[cursor + 2..cursor + 4])? & 0xfff9 != 0 {
                        return None;
                    }
                    8
                } else {
                    (usize::from(packet[cursor + 1]) + 1) * 8
                };
                cursor = cursor.checked_add(len)?;
                if cursor > end {
                    return None;
                }
                next = after;
            }
            if matches!(next, 0 | 43 | 44 | 50 | 51 | 59 | 60) {
                return None;
            }
            Some(IpPacket {
                source: src,
                target: dst,
                protocol: next,
                hop_limit: packet[7],
                body: &packet[cursor..end],
            })
        }
        _ => None,
    }
}

fn match_quoted(packet: &[u8], probe: &ProbeIdentity) -> bool {
    let Some(ip) = raw_ip_packet(packet, true) else {
        return false;
    };
    if ip.source != probe.local || ip.target != probe.target || ip.body.len() < 8 {
        return false;
    }
    // Quoted ICMP errors contain at least the original IP header plus
    // the first 8 ICMP bytes; match the original request's unpredictable
    // identifier/sequence rather than trusting only its source address.
    if probe.transport == ProbeTransport::IcmpEcho {
        let protocol = if ip.source.is_ipv4() { 1 } else { 58 };
        let request_type = if ip.source.is_ipv4() { 8 } else { 128 };
        return ip.protocol == protocol
            && ip.body[0] == request_type
            && ip.body[1] == 0
            && probe.echo_key
                == Some((
                    be16(&ip.body[4..6]).unwrap_or(u16::MAX),
                    be16(&ip.body[6..8]).unwrap_or(u16::MAX),
                ));
    }
    let expected = match probe.transport {
        ProbeTransport::TcpSyn => 6,
        ProbeTransport::Udp => 17,
        _ => return false,
    };
    if ip.protocol != expected
        || be16(&ip.body[..2]) != Some(probe.local_port)
        || be16(&ip.body[2..4]) != Some(probe.target_port)
    {
        return false;
    }
    if probe.transport == ProbeTransport::TcpSyn {
        let seq = u32::from_be_bytes(ip.body[4..8].try_into().expect("length checked"));
        return probe.syn_sequence == Some(seq);
    }
    true
}

/// Correlate raw IPv4/IPv6 response bytes against one outstanding probe.
/// Positive evidence is neither host authentication nor an OS fingerprint.
/// ICMP errors are evidence of network treatment, not proof of TCP filtering.
pub fn correlate_ip_response(packet: &[u8], probe: &ProbeIdentity) -> Option<ReplyEvidence> {
    let ip = raw_ip_packet(packet, false)?;
    if ip.target != probe.local {
        return None;
    }
    match (ip.protocol, probe.transport) {
        (6, ProbeTransport::TcpSyn) if ip.source == probe.target => {
            if ip.body.len() < 20
                || usize::from(ip.body[12] >> 4) * 4 > ip.body.len()
                || ip.body[12] >> 4 < 5
                || be16(&ip.body[..2]) != Some(probe.target_port)
                || be16(&ip.body[2..4]) != Some(probe.local_port)
            {
                return None;
            }
            let ack = u32::from_be_bytes(ip.body[8..12].try_into().ok()?);
            let flags = ip.body[13];
            if flags & 0x10 == 0 || ack != probe.syn_sequence?.wrapping_add(1) {
                return None;
            }
            if flags & 0x12 == 0x12 && flags & 0x04 == 0 {
                Some(ReplyEvidence::TcpSynAck)
            } else if flags & 0x04 != 0 {
                Some(ReplyEvidence::TcpReset)
            } else {
                None
            }
        }
        (17, ProbeTransport::Udp) if ip.source == probe.target => {
            if ip.body.len() < 8
                || be16(&ip.body[..2]) != Some(probe.target_port)
                || be16(&ip.body[2..4]) != Some(probe.local_port)
            {
                return None;
            }
            let size = usize::from(be16(&ip.body[4..6])?);
            (size >= 8 && size <= ip.body.len()).then_some(ReplyEvidence::UdpResponse)
        }
        (1, ProbeTransport::IcmpEcho) if ip.source == probe.target => {
            if ip.body.len() < 8 || ip.body[0] != 0 || ip.body[1] != 0 {
                return None;
            }
            (probe.echo_key == Some((be16(&ip.body[4..6])?, be16(&ip.body[6..8])?)))
                .then_some(ReplyEvidence::IcmpEcho)
        }
        (58, ProbeTransport::IcmpEcho) if ip.source == probe.target => {
            if ip.body.len() < 8 || ip.body[0] != 129 || ip.body[1] != 0 {
                return None;
            }
            (probe.echo_key == Some((be16(&ip.body[4..6])?, be16(&ip.body[6..8])?)))
                .then_some(ReplyEvidence::IcmpEcho)
        }
        (1, ProbeTransport::TcpSyn | ProbeTransport::Udp | ProbeTransport::IcmpEcho)
            if ip.body.len() >= 8
                && matches!(ip.body[0], 3 | 11)
                && match_quoted(&ip.body[8..], probe) =>
        {
            Some(ReplyEvidence::IcmpV4Error {
                kind: ip.body[0],
                code: ip.body[1],
            })
        }
        (58, ProbeTransport::TcpSyn | ProbeTransport::Udp | ProbeTransport::IcmpEcho)
            if ip.body.len() >= 8
                && matches!(ip.body[0], 1 | 3)
                && match_quoted(&ip.body[8..], probe) =>
        {
            Some(ReplyEvidence::IcmpV6Error {
                kind: ip.body[0],
                code: ip.body[1],
            })
        }
        _ => None,
    }
}

/// Preserve the observed outer IP responder when correlating an exact
/// Ethernet response. This supports honest hop-by-hop route observations:
/// intermediate routers may legitimately send a matched ICMP Time Exceeded
/// error while the quoted original probe still targets a different host.
///
/// A router IP is a network-reported claim, not authenticated identity.
pub fn correlate_ethernet_response_with_origin(
    frame: &[u8],
    probe: &ProbeIdentity,
) -> Option<(IpAddr, ReplyEvidence)> {
    let evidence = correlate_ethernet_response(frame, probe)?;
    if !matches!(
        evidence,
        ReplyEvidence::IcmpEcho
            | ReplyEvidence::IcmpV4Error { .. }
            | ReplyEvidence::IcmpV6Error { .. }
            | ReplyEvidence::TcpSynAck
            | ReplyEvidence::TcpReset
            | ReplyEvidence::UdpResponse
    ) {
        return None;
    }
    if frame.len() < 14 {
        return None;
    }
    let mut kind = be16(&frame[12..14])?;
    let mut cursor = 14usize;
    for _ in 0..2 {
        if !matches!(kind, 0x8100 | 0x88a8) {
            break;
        }
        kind = be16(frame.get(cursor + 2..cursor + 4)?)?;
        cursor += 4;
    }
    if matches!(kind, 0x8100 | 0x88a8) || !matches!(kind, 0x0800 | 0x86dd) {
        return None;
    }
    let ip = raw_ip_packet(frame.get(cursor..)?, false)?;
    if ip.source.is_unspecified() || ip.source.is_multicast() {
        return None;
    }
    Some((ip.source, evidence))
}

/// Exact Ethernet II frames with up to two VLAN tags. Refuses unsupported
/// link types; callers must not pass loopback cooked or radiotap frames.
pub fn correlate_ethernet_response(frame: &[u8], probe: &ProbeIdentity) -> Option<ReplyEvidence> {
    if frame.len() < 14 {
        return None;
    }
    let sender_mac: [u8; 6] = frame[6..12].try_into().ok()?;
    let mut kind = be16(&frame[12..14])?;
    let mut cursor = 14usize;
    for _ in 0..2 {
        if !matches!(kind, 0x8100 | 0x88a8) {
            break;
        }
        if frame.len() < cursor + 4 {
            return None;
        }
        kind = be16(&frame[cursor + 2..cursor + 4])?;
        cursor += 4;
    }
    // Never accidentally decode a third stacked VLAN or 802.3 length field.
    if matches!(kind, 0x8100 | 0x88a8) {
        return None;
    }
    match (kind, probe.transport) {
        (0x86dd, ProbeTransport::NeighborDiscovery) => {
            let ip = raw_ip_packet(frame.get(cursor..)?, false)?;
            if ip.protocol != 58
                || ip.hop_limit != 255
                || ip.source != probe.target
                || ip.target != probe.local
                || ip.body.len() != 32
                || ip.body[0] != 136
                || ip.body[1] != 0
                || ip.body[24] != 2
                || ip.body[25] != 1
            {
                return None;
            }
            let IpAddr::V6(target) = probe.target else {
                return None;
            };
            let IpAddr::V6(local) = probe.local else {
                return None;
            };
            if ip.body[8..24] != target.octets()
                || ip.body[26..32] != sender_mac
                || sender_mac == [0; 6]
                || sender_mac[0] & 1 != 0
            {
                return None;
            }
            let mut pseudo = [0u8; 40];
            pseudo[..16].copy_from_slice(&target.octets());
            pseudo[16..32].copy_from_slice(&local.octets());
            pseudo[32..36].copy_from_slice(&32u32.to_be_bytes());
            pseudo[39] = 58;
            let mut sum = 0u32;
            for bytes in [&pseudo[..], ip.body] {
                for part in bytes.chunks_exact(2) {
                    sum += u32::from(u16::from_be_bytes([part[0], part[1]]));
                }
            }
            while sum >> 16 != 0 {
                sum = (sum & 0xffff) + (sum >> 16);
            }
            if sum as u16 != 0xffff {
                return None;
            }
            Some(ReplyEvidence::NeighborAdvertisement {
                hardware_address: sender_mac,
            })
        }
        (0x0806, ProbeTransport::Arp) => {
            let bytes = frame.get(cursor..cursor + 28)?;
            if be16(&bytes[0..2]) != Some(1)
                || be16(&bytes[2..4]) != Some(0x0800)
                || bytes[4] != 6
                || bytes[5] != 4
                || be16(&bytes[6..8]) != Some(2)
            {
                return None;
            }
            let source: [u8; 4] = bytes[14..18].try_into().ok()?;
            let target: [u8; 4] = bytes[24..28].try_into().ok()?;
            if Some(probe.target) != Some(IpAddr::V4(Ipv4Addr::from(source)))
                || Some(probe.local) != Some(IpAddr::V4(Ipv4Addr::from(target)))
            {
                return None;
            }
            let arp_mac: [u8; 6] = bytes[8..14].try_into().ok()?;
            if arp_mac != sender_mac || arp_mac == [0; 6] || arp_mac[0] & 1 != 0 {
                return None;
            }
            Some(ReplyEvidence::ArpReply {
                hardware_address: arp_mac,
            })
        }
        (0x0800, _) if matches!(probe.local, IpAddr::V4(_)) => {
            correlate_ip_response(frame.get(cursor..)?, probe)
        }
        (0x86dd, _) if matches!(probe.local, IpAddr::V6(_)) => {
            correlate_ip_response(frame.get(cursor..)?, probe)
        }
        _ => None,
    }
}

#[cfg(test)]

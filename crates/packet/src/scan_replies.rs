    fn tcp_probe() -> ProbeIdentity {
        ProbeIdentity {
            local: "192.0.2.1".parse().unwrap(),
            target: "192.0.2.2".parse().unwrap(),
            transport: ProbeTransport::TcpSyn,
            local_port: 40000,
            target_port: 443,
            syn_sequence: Some(u32::MAX),
            echo_key: None,
        }
    }
    fn v4(proto: u8, src: [u8; 4], dst: [u8; 4], body: &[u8]) -> Vec<u8> {
        let mut bytes = vec![0u8; 20 + body.len()];
        bytes[0] = 0x45;
        let size = u16::try_from(bytes.len()).unwrap();
        bytes[2..4].copy_from_slice(&size.to_be_bytes());
        bytes[9] = proto;
        bytes[12..16].copy_from_slice(&src);
        bytes[16..20].copy_from_slice(&dst);
        bytes[20..].copy_from_slice(body);
        bytes
    }
    fn tcp_reply(flags: u8) -> Vec<u8> {
        let mut bytes = vec![0u8; 20];
        bytes[0..2].copy_from_slice(&443u16.to_be_bytes());
        bytes[2..4].copy_from_slice(&40000u16.to_be_bytes());
        bytes[8..12].copy_from_slice(&0u32.to_be_bytes());
        bytes[12] = 0x50;
        bytes[13] = flags;
        bytes
    }
    fn v6(next: u8, src: Ipv6Addr, dst: Ipv6Addr, data: &[u8]) -> Vec<u8> {
        let mut bytes = vec![0u8; 40 + data.len()];
        bytes[0] = 0x60;
        bytes[4..6].copy_from_slice(&(data.len() as u16).to_be_bytes());
        bytes[6] = next;
        bytes[8..24].copy_from_slice(&src.octets());
        bytes[24..40].copy_from_slice(&dst.octets());
        bytes[40..].copy_from_slice(data);
        bytes
    }

    #[test]
    fn traceroute_origin_preserves_matched_router_and_rejects_wrong_identity() {
        let id = ProbeIdentity {
            local: "192.0.2.1".parse().unwrap(),
            target: "198.51.100.9".parse().unwrap(),
            transport: ProbeTransport::IcmpEcho,
            local_port: 0,
            target_port: 0,
            syn_sequence: None,
            echo_key: Some((0x1234, 0xabcd)),
        };
        let quoted_echo = [8, 0, 0, 0, 0x12, 0x34, 0xab, 0xcd];
        let original = v4(1, [192, 0, 2, 1], [198, 51, 100, 9], &quoted_echo);
        let mut error = vec![11, 0, 0, 0, 0, 0, 0, 0];
        error.extend_from_slice(&original);
        let response = v4(1, [192, 0, 2, 254], [192, 0, 2, 1], &error);
        let mut frame = vec![0u8; 14];
        frame[12..14].copy_from_slice(&0x0800u16.to_be_bytes());
        frame.extend_from_slice(&response);
        assert_eq!(
            correlate_ethernet_response_with_origin(&frame, &id),
            Some((
                "192.0.2.254".parse().unwrap(),
                ReplyEvidence::IcmpV4Error { kind: 11, code: 0 },
            ))
        );
        let mut wrong = id;
        wrong.echo_key = Some((0x1234, 0xabce));
        assert_eq!(
            correlate_ethernet_response_with_origin(&frame, &wrong),
            None
        );
        frame[12..14].copy_from_slice(&0x0806u16.to_be_bytes());
        assert_eq!(correlate_ethernet_response_with_origin(&frame, &id), None);
    }


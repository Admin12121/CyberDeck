    #[test]
    fn ipv6_icmp_echo_and_extension_chain_are_strict() {
        let local: Ipv6Addr = "2001:db8::1".parse().unwrap();
        let remote: Ipv6Addr = "2001:db8::2".parse().unwrap();
        let mut id = tcp_probe();
        id.local = IpAddr::V6(local);
        id.target = IpAddr::V6(remote);
        id.transport = ProbeTransport::IcmpEcho;
        id.echo_key = Some((123, 456));
        let echo = [129, 0, 0, 0, 0, 123, 1, 200];
        assert_eq!(
            correlate_ip_response(&v6(58, remote, local, &echo), &id),
            Some(ReplyEvidence::IcmpEcho)
        );
        let mut other = echo;
        other[7] = 201;
        assert_eq!(
            correlate_ip_response(&v6(58, remote, local, &other), &id),
            None
        );
        id.transport = ProbeTransport::TcpSyn;
        let mut extension = [0u8; 8];
        extension[0] = 6;
        let mut data = extension.to_vec();
        data.extend(tcp_reply(0x12));
        assert_eq!(
            correlate_ip_response(&v6(60, remote, local, &data), &id),
            Some(ReplyEvidence::TcpSynAck)
        );
        data[3] = 1;
        let mut too_short = v6(60, remote, local, &data);
        too_short[41] = 4; // extension requires 40 bytes, not present
        assert_eq!(correlate_ip_response(&too_short, &id), None);
    }

    #[test]
    fn matched_arp_reply_uses_sender_mac_and_protocol_pair() {
        let mut id = tcp_probe();
        id.transport = ProbeTransport::Arp;
        let mac = [0x02, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e];
        let mut frame = vec![0u8; 42];
        frame[6..12].copy_from_slice(&mac);
        frame[12..14].copy_from_slice(&0x0806u16.to_be_bytes());
        frame[14..16].copy_from_slice(&1u16.to_be_bytes());
        frame[16..18].copy_from_slice(&0x0800u16.to_be_bytes());
        frame[18] = 6;
        frame[19] = 4;
        frame[20..22].copy_from_slice(&2u16.to_be_bytes());
        frame[22..28].copy_from_slice(&mac);
        frame[28..32].copy_from_slice(&[192, 0, 2, 2]);
        frame[32..38].copy_from_slice(&[0u8; 6]);
        frame[38..42].copy_from_slice(&[192, 0, 2, 1]);
        assert_eq!(
            correlate_ethernet_response(&frame, &id),
            Some(ReplyEvidence::ArpReply {
                hardware_address: mac
            })
        );
        let mut wrong = frame.clone();
        wrong[6] ^= 1;
        assert_eq!(correlate_ethernet_response(&wrong, &id), None);
        let mut vlan = Vec::from(&frame[..12]);
        vlan.extend_from_slice(&[0x81, 0, 0, 1, 0x08, 0x06]);
        vlan.extend_from_slice(&frame[14..]);
        assert_eq!(
            correlate_ethernet_response(&vlan, &id),
            Some(ReplyEvidence::ArpReply {
                hardware_address: mac
            })
        );
    }
